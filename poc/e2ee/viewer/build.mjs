// Bundles the viewer page script with esbuild (no minification, so the
// result stays reviewable) and writes the licence notices of the third-party
// code that ends up inside the bundle.
//
//   npm run build      ->  viewer/viewer.bundle.js, viewer/THIRD-PARTY-NOTICES.txt

import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const at = (relative) => fileURLToPath(new URL(relative, import.meta.url));
const bundled = ['@hpke/core', '@hpke/common']; // everything else in the bundle is viewer/src

const notices = ['Third-party code contained in viewer.bundle.js', ''];
const versions = [];
for (const name of bundled) {
  const dir = `../node_modules/${name}/`;
  const { version } = JSON.parse(await readFile(at(dir + 'package.json'), 'utf8'));
  versions.push(`${name} ${version}`);
  notices.push('='.repeat(72), `${name} ${version}`, '='.repeat(72), '', (await readFile(at(dir + 'LICENSE'), 'utf8')).trim(), '');
}

const result = await build({
  entryPoints: [at('src/main.js')],
  outfile: at('viewer.bundle.js'),
  bundle: true,
  format: 'iife',
  target: 'es2022',
  charset: 'utf8',
  metafile: true,
  logLevel: 'warning',
  banner: {
    js:
      '/* DronStream E2EE PoC viewer bundle. Generated by viewer/build.mjs (esbuild) from viewer/src - do not edit.\n' +
      `   Contains ${versions.join(' and ')} (MIT License), see THIRD-PARTY-NOTICES.txt. */`,
  },
});

// Fail the build if anything unexpected was pulled into the page script.
const unexpected = Object.keys(result.metafile.inputs).filter(
  (input) => !input.startsWith('viewer/src/') && !bundled.some((name) => input.startsWith(`node_modules/${name}/`)) && !input.startsWith('(disabled):'),
);
if (unexpected.length > 0) {
  console.error('unexpected modules in the bundle:\n  ' + unexpected.join('\n  '));
  process.exit(1);
}

await writeFile(at('THIRD-PARTY-NOTICES.txt'), notices.join('\n') + '\n');
const size = result.metafile.outputs[Object.keys(result.metafile.outputs)[0]].bytes;
console.log(`viewer/viewer.bundle.js: ${size} bytes, ${Object.keys(result.metafile.inputs).length} modules (${versions.join(', ')})`);
