package mtx

import (
	"fmt"
	"strings"

	"gopkg.in/yaml.v3"
)

// ConfInput are the values DronStream controls in the generated mediamtx.yml.
type ConfInput struct {
	LogLevel        string
	LogFile         string
	HookURL         string // http://127.0.0.1:9180/internal/mtx-auth/<secret>
	APIAddr         string
	WebRTCHTTPAddr  string
	WebRTCUDPAddr   string
	WebRTCTCPAddr   string
	WebRTCHosts     []string
	WebRTCIfaces    bool
	RTMPAddr        string
	RTMPSAddr       string // "" = RTMPS off
	TLSCert, TLSKey string
}

// Render produces a locked-down MediaMTX config:
//   - every publish/read is authorised by the DronStream hook (authMethod http)
//   - only "api" is excluded from the hook and the API listens on loopback
//   - HLS, RTSP, SRT, MoQ, playback, metrics, pprof and recording are disabled,
//     so no alternative playback path can bypass permissions
//   - overridePublisher=false: a second publisher cannot silently replace the first
func Render(in ConfInput) ([]byte, error) {
	rtmpEnc := "no"
	if in.RTMPSAddr != "" {
		rtmpEnc = "optional"
	}
	rtmpOn := in.RTMPAddr != "" || in.RTMPSAddr != ""
	rtmpAddr := in.RTMPAddr
	if rtmpAddr == "" {
		// RTMPS only: MediaMTX still needs a value; bind plain RTMP to loopback.
		rtmpAddr = "127.0.0.1:19350"
		if in.RTMPSAddr != "" {
			rtmpEnc = "strict"
		}
	}
	hosts := in.WebRTCHosts
	if hosts == nil {
		hosts = []string{}
	}
	logDest := []string{"stdout"}
	m := map[string]any{
		"logLevel":        nz(in.LogLevel, "info"),
		"logDestinations": logDest,
		"readTimeout":     "10s",
		"writeTimeout":    "10s",
		"authMethod":      "http",
		"authHTTPAddress": in.HookURL,
		"authHTTPExclude": []map[string]any{{"action": "api"}},
		"api":             true,
		"apiAddress":      in.APIAddr,
		"apiAllowOrigins": []string{},
		"metrics":         false,
		"pprof":           false,
		"playback":        false,
		"rtsp":            false,
		"rtmp":            rtmpOn,
		"rtmpAddress":     rtmpAddr,
		"rtmpEncryption":  rtmpEnc,
		"hls":             false,
		"srt":             false,
		"moq":             false,
		"webrtc":          true,
		"webrtcAddress":   in.WebRTCHTTPAddr,
		"webrtcEncryption": false, // signalling is loopback-only behind the HTTPS proxy
		"webrtcAllowOrigins":         []string{},
		"webrtcLocalUDPAddress":      in.WebRTCUDPAddr,
		"webrtcLocalTCPAddress":      in.WebRTCTCPAddr,
		"webrtcIPsFromInterfaces":    in.WebRTCIfaces,
		"webrtcAdditionalHosts":      hosts,
		"webrtcICEServers2":          []any{},
		"webrtcHandshakeTimeout":     "10s",
		"pathDefaults": map[string]any{
			"source":            "publisher",
			"overridePublisher": false,
			"record":            false,
		},
		"paths": map[string]any{
			// Only "live/<slug>" and "live/<slug>/<key>"; anything else has no config.
			"~^live/[a-z0-9][a-z0-9_-]{1,39}(/[A-Za-z0-9]{8,128})?$": map[string]any{},
		},
	}
	if in.RTMPSAddr != "" {
		m["rtmpsAddress"] = in.RTMPSAddr
		m["rtmpServerKey"] = in.TLSKey
		m["rtmpServerCert"] = in.TLSCert
	}
	b, err := yaml.Marshal(m)
	if err != nil {
		return nil, err
	}
	head := fmt.Sprintf("# GENERATED by DronStream on every start. Do not edit — change config/dronstream.yaml instead.\n# MediaMTX %s\n", PinnedVersion)
	return []byte(head + string(b)), nil
}

func nz(v, d string) string {
	if strings.TrimSpace(v) == "" {
		return d
	}
	return v
}
