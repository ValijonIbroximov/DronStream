// Package tlsutil provides the HTTPS certificate: an admin-supplied
// certificate, Let's Encrypt (ACME) for a real domain, or an automatically
// generated self-signed certificate for local/LAN use.
package tlsutil

import (
	"crypto/ecdsa"
	"crypto/elliptic"
	"crypto/rand"
	"crypto/sha256"
	"crypto/tls"
	"crypto/x509"
	"crypto/x509/pkix"
	"encoding/hex"
	"encoding/pem"
	"errors"
	"math/big"
	"net"
	"os"
	"path/filepath"
	"time"

	"golang.org/x/crypto/acme/autocert"
)

type Info struct {
	Mode        string    `json:"mode"` // file | self-signed | acme
	CertFile    string    `json:"certFile,omitempty"`
	KeyFile     string    `json:"-"`
	NotAfter    time.Time `json:"notAfter,omitempty"`
	Fingerprint string    `json:"fingerprintSHA256,omitempty"`
	Names       []string  `json:"names,omitempty"`
}

// Load returns a TLS config. Files live in secretsDir as tls.crt / tls.key.
func Load(secretsDir string, hosts []string, acmeDomain, acmeEmail string) (*tls.Config, *autocert.Manager, Info, error) {
	crt := filepath.Join(secretsDir, "tls.crt")
	key := filepath.Join(secretsDir, "tls.key")
	base := &tls.Config{MinVersion: tls.VersionTLS12}
	if acmeDomain != "" {
		m := &autocert.Manager{
			Prompt:     autocert.AcceptTOS,
			HostPolicy: autocert.HostWhitelist(acmeDomain),
			Cache:      autocert.DirCache(filepath.Join(secretsDir, "acme")),
			Email:      acmeEmail,
		}
		cfg := m.TLSConfig()
		cfg.MinVersion = tls.VersionTLS12
		return cfg, m, Info{Mode: "acme", Names: []string{acmeDomain}}, nil
	}
	mode := "file"
	if _, err := os.Stat(crt); errors.Is(err, os.ErrNotExist) {
		if err := generateSelfSigned(crt, key, hosts); err != nil {
			return nil, nil, Info{}, err
		}
		mode = "self-signed"
	} else if isSelfMarked(crt) {
		mode = "self-signed"
	}
	pair, err := tls.LoadX509KeyPair(crt, key)
	if err != nil {
		return nil, nil, Info{}, err
	}
	leaf, _ := x509.ParseCertificate(pair.Certificate[0])
	base.Certificates = []tls.Certificate{pair}
	fp := sha256.Sum256(pair.Certificate[0])
	info := Info{Mode: mode, CertFile: crt, KeyFile: key, Fingerprint: hex.EncodeToString(fp[:])}
	if leaf != nil {
		info.NotAfter = leaf.NotAfter
		info.Names = leaf.DNSNames
		for _, ip := range leaf.IPAddresses {
			info.Names = append(info.Names, ip.String())
		}
	}
	return base, nil, info, nil
}

func isSelfMarked(crt string) bool {
	_, err := os.Stat(crt + ".selfsigned")
	return err == nil
}

func generateSelfSigned(crtPath, keyPath string, hosts []string) error {
	priv, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		return err
	}
	serial, _ := rand.Int(rand.Reader, new(big.Int).Lsh(big.NewInt(1), 120))
	tmpl := x509.Certificate{
		SerialNumber: serial,
		Subject:      pkix.Name{CommonName: "DronStream server", Organization: []string{"DronStream (self-signed)"}},
		NotBefore:    time.Now().Add(-time.Hour),
		NotAfter:     time.Now().Add(397 * 24 * time.Hour),
		KeyUsage:     x509.KeyUsageDigitalSignature,
		ExtKeyUsage:  []x509.ExtKeyUsage{x509.ExtKeyUsageServerAuth},
	}
	seen := map[string]bool{}
	add := func(h string) {
		if h == "" || seen[h] {
			return
		}
		seen[h] = true
		if ip := net.ParseIP(h); ip != nil {
			tmpl.IPAddresses = append(tmpl.IPAddresses, ip)
		} else {
			tmpl.DNSNames = append(tmpl.DNSNames, h)
		}
	}
	for _, h := range append([]string{"localhost", "127.0.0.1"}, hosts...) {
		add(h)
	}
	if hn, err := os.Hostname(); err == nil {
		add(hn)
	}
	addrs, _ := net.InterfaceAddrs()
	for _, a := range addrs {
		if n, ok := a.(*net.IPNet); ok && n.IP.To4() != nil && !n.IP.IsLinkLocalUnicast() {
			add(n.IP.String())
		}
	}
	der, err := x509.CreateCertificate(rand.Reader, &tmpl, &tmpl, &priv.PublicKey, priv)
	if err != nil {
		return err
	}
	kb, err := x509.MarshalECPrivateKey(priv)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(crtPath), 0o700); err != nil {
		return err
	}
	if err := os.WriteFile(keyPath, pem.EncodeToMemory(&pem.Block{Type: "EC PRIVATE KEY", Bytes: kb}), 0o600); err != nil {
		return err
	}
	if err := os.WriteFile(crtPath, pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: der}), 0o644); err != nil {
		return err
	}
	return os.WriteFile(crtPath+".selfsigned", []byte("generated by DronStream; replace tls.crt/tls.key with a CA-issued certificate and delete this marker\n"), 0o644)
}
