// Package mediafiles stores uploaded images and videos outside any public
// directory, validates their real format (magic bytes / container parsing,
// not the file extension) and produces image thumbnails.
//
// Accepted:
//   images: PNG, JPEG, GIF, WebP (≤ 50 megapixels)
//   videos: MP4/MOV (ISO-BMFF) with H.264 (avc1/avc3), AV1 (av01) or VP9 (vp09)
//           video; WebM with VP8/VP9/AV1.
// Rejected with a clear message: SVG, HTML/XML/scripts, H.265/HEVC and any
// other codec browsers cannot play without transcoding (no transcoding is
// done, so FFmpeg is not needed at runtime).
package mediafiles

import (
	"bufio"
	"bytes"
	"crypto/rand"
	"crypto/sha256"
	"encoding/binary"
	"encoding/hex"
	"errors"
	"fmt"
	"image"
	_ "image/gif"
	"image/jpeg"
	_ "image/png"
	"io"
	"os"
	"path/filepath"
	"regexp"

	"golang.org/x/image/draw"
	_ "golang.org/x/image/webp"
)

type Store struct {
	Dir           string
	MaxImageBytes int64
	MaxVideoBytes int64
}

type Meta struct {
	FileID   string
	Kind     string // image | video
	Mime     string
	Codec    string
	Size     int64
	Width    int
	Height   int
	SHA256   string
	HasThumb bool
}

// UserError is an upload rejection with an Uzbek message.
type UserError struct{ Msg string }

func (e *UserError) Error() string { return e.Msg }

func uerr(f string, a ...any) error { return &UserError{Msg: fmt.Sprintf(f, a...)} }

var idRe = regexp.MustCompile(`^[a-f0-9]{32}$`)

// Path maps a stored file id to its path. Ids are generated by us; clients
// never supply paths.
func (s *Store) Path(id string) (string, error) {
	if !idRe.MatchString(id) {
		return "", errors.New("bad file id")
	}
	return filepath.Join(s.Dir, id), nil
}

func (s *Store) ThumbPath(id string) (string, error) {
	p, err := s.Path(id)
	return p + ".thumb.jpg", err
}

func (s *Store) Remove(id string) {
	if p, err := s.Path(id); err == nil {
		os.Remove(p)
		os.Remove(p + ".thumb.jpg")
	}
}

// Save streams r to disk (size-limited), validates the real format and
// returns metadata. kindHint is "image" or "video" (from the admin's choice);
// the detected format must match it.
func (s *Store) Save(r io.Reader, kindHint string) (*Meta, error) {
	if err := os.MkdirAll(s.Dir, 0o700); err != nil {
		return nil, err
	}
	limit := s.MaxVideoBytes
	if kindHint == "image" {
		limit = s.MaxImageBytes
	}
	b := make([]byte, 16)
	rand.Read(b)
	id := hex.EncodeToString(b)
	final := filepath.Join(s.Dir, id)
	tmp := final + ".upload"
	f, err := os.OpenFile(tmp, os.O_CREATE|os.O_EXCL|os.O_WRONLY, 0o600)
	if err != nil {
		return nil, err
	}
	h := sha256.New()
	n, err := io.Copy(io.MultiWriter(f, h), io.LimitReader(r, limit+1))
	f.Close()
	if err != nil {
		os.Remove(tmp)
		return nil, err
	}
	if n > limit {
		os.Remove(tmp)
		return nil, uerr("Fayl juda katta (chegara %d MB)", limit>>20)
	}
	if n == 0 {
		os.Remove(tmp)
		return nil, uerr("Fayl bo'sh")
	}
	m, err := Inspect(tmp)
	if err != nil {
		os.Remove(tmp)
		return nil, err
	}
	if m.Kind != kindHint {
		os.Remove(tmp)
		return nil, uerr("Fayl turi tanlangan turga mos emas (aniqlangan: %s)", m.Mime)
	}
	m.FileID, m.Size, m.SHA256 = id, n, hex.EncodeToString(h.Sum(nil))
	if err := os.Rename(tmp, final); err != nil {
		os.Remove(tmp)
		return nil, err
	}
	if m.Kind == "image" {
		if err := makeThumb(final, final+".thumb.jpg"); err == nil {
			m.HasThumb = true
		}
	}
	return m, nil
}

// Inspect detects the real type of a file on disk.
func Inspect(path string) (*Meta, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	head := make([]byte, 512)
	k, _ := io.ReadFull(f, head)
	head = head[:k]
	low := bytes.ToLower(bytes.TrimLeft(head, " \t\r\n\xef\xbb\xbf"))
	switch {
	case bytes.HasPrefix(low, []byte("<svg")) || bytes.Contains(low, []byte("<svg")):
		return nil, uerr("SVG qabul qilinmaydi (faol kontent bo'lishi mumkin)")
	case bytes.HasPrefix(low, []byte("<")) || bytes.Contains(low, []byte("<html")) || bytes.Contains(low, []byte("<script")):
		return nil, uerr("HTML/XML yoki skript fayllar qabul qilinmaydi")
	}
	var mime string
	switch {
	case bytes.HasPrefix(head, []byte("\x89PNG\r\n\x1a\n")):
		mime = "image/png"
	case bytes.HasPrefix(head, []byte{0xFF, 0xD8, 0xFF}):
		mime = "image/jpeg"
	case bytes.HasPrefix(head, []byte("GIF87a")) || bytes.HasPrefix(head, []byte("GIF89a")):
		mime = "image/gif"
	case len(head) >= 12 && string(head[0:4]) == "RIFF" && string(head[8:12]) == "WEBP":
		mime = "image/webp"
	}
	if mime != "" {
		f.Seek(0, io.SeekStart)
		cfg, _, err := image.DecodeConfig(bufio.NewReader(f))
		if err != nil {
			return nil, uerr("Rasm faylini o'qib bo'lmadi (buzilgan yoki noto'g'ri format)")
		}
		if cfg.Width <= 0 || cfg.Height <= 0 || int64(cfg.Width)*int64(cfg.Height) > 50_000_000 {
			return nil, uerr("Rasm o'lchami ruxsat etilgan chegaradan katta (50 megapiksel)")
		}
		return &Meta{Kind: "image", Mime: mime, Width: cfg.Width, Height: cfg.Height}, nil
	}
	if len(head) >= 12 && string(head[4:8]) == "ftyp" {
		codec, err := mp4VideoCodec(f)
		if err != nil {
			return nil, err
		}
		switch codec {
		case "avc1", "avc3":
			return &Meta{Kind: "video", Mime: "video/mp4", Codec: "H.264"}, nil
		case "av01":
			return &Meta{Kind: "video", Mime: "video/mp4", Codec: "AV1"}, nil
		case "vp09":
			return &Meta{Kind: "video", Mime: "video/mp4", Codec: "VP9"}, nil
		case "hvc1", "hev1":
			return nil, uerr("H.265/HEVC video ko'p brauzerlarda ijro etilmaydi. Videoni H.264 (MP4) ga o'tkazib yuklang")
		case "":
			return nil, uerr("MP4 faylda video trek topilmadi")
		default:
			return nil, uerr("Video kodek (%s) brauzerlarda qo'llab-quvvatlanmaydi. H.264 MP4 yoki VP9/AV1 WebM yuklang", codec)
		}
	}
	if bytes.HasPrefix(head, []byte{0x1A, 0x45, 0xDF, 0xA3}) {
		if !bytes.Contains(head, []byte("webm")) {
			return nil, uerr("Faqat WebM (Matroska MKV emas) qo'llab-quvvatlanadi")
		}
		codec, err := webmCodec(f)
		if err != nil {
			return nil, err
		}
		return &Meta{Kind: "video", Mime: "video/webm", Codec: codec}, nil
	}
	return nil, uerr("Fayl formati qo'llab-quvvatlanmaydi. Rasm: PNG, JPEG, GIF, WebP. Video: MP4 (H.264/AV1/VP9), WebM (VP8/VP9/AV1)")
}

// mp4VideoCodec walks ISO-BMFF boxes: moov/trak/mdia/(hdlr=vide)/minf/stbl/stsd.
func mp4VideoCodec(f *os.File) (string, error) {
	st, err := f.Stat()
	if err != nil {
		return "", err
	}
	var walk func(off, end int64, depth int) (string, error)
	readHdr := func(off int64) (size int64, typ string, hdr int64, err error) {
		b := make([]byte, 16)
		if _, err = f.ReadAt(b[:8], off); err != nil {
			return
		}
		size = int64(binary.BigEndian.Uint32(b[:4]))
		typ = string(b[4:8])
		hdr = 8
		if size == 1 {
			if _, err = f.ReadAt(b[8:16], off+8); err != nil {
				return
			}
			size = int64(binary.BigEndian.Uint64(b[8:16]))
			hdr = 16
		} else if size == 0 {
			size = st.Size() - off
		}
		if size < hdr {
			err = errors.New("bad box")
		}
		return
	}
	var lastHandler string
	walk = func(off, end int64, depth int) (string, error) {
		if depth > 8 {
			return "", nil
		}
		trakCodec := ""
		for off+8 <= end {
			size, typ, hdr, err := readHdr(off)
			if err != nil || off+size > end {
				return trakCodec, nil
			}
			switch typ {
			case "moov", "trak", "mdia", "minf", "stbl":
				if typ == "trak" {
					lastHandler = ""
				}
				c, err := walk(off+hdr, off+size, depth+1)
				if err != nil {
					return "", err
				}
				if typ == "trak" && c != "" && lastHandler == "vide" {
					return c, nil
				}
				if typ != "trak" && c != "" {
					trakCodec = c
				}
			case "hdlr":
				b := make([]byte, 4)
				f.ReadAt(b, off+hdr+8)
				lastHandler = string(b)
			case "stsd":
				b := make([]byte, 8)
				// version/flags(4) entry_count(4) then first sample entry: size(4) type(4)
				f.ReadAt(b, off+hdr+8)
				return string(b[4:8]), nil
			}
			off += size
		}
		return trakCodec, nil
	}
	c, err := walk(0, st.Size(), 0)
	if err != nil {
		return "", uerr("MP4 faylni tahlil qilib bo'lmadi")
	}
	return c, nil
}

func webmCodec(f *os.File) (string, error) {
	f.Seek(0, io.SeekStart)
	buf := make([]byte, 4<<20)
	n, _ := io.ReadFull(f, buf)
	buf = buf[:n]
	for _, c := range []struct{ id, name string }{{"V_VP9", "VP9"}, {"V_VP8", "VP8"}, {"V_AV1", "AV1"}} {
		if bytes.Contains(buf, []byte(c.id)) {
			return c.name, nil
		}
	}
	if bytes.Contains(buf, []byte("V_MPEGH/ISO/HEVC")) || bytes.Contains(buf, []byte("V_MPEG4")) {
		return "", uerr("WebM ichidagi video kodek brauzerlarda qo'llab-quvvatlanmaydi (VP8/VP9/AV1 kerak)")
	}
	return "", uerr("WebM faylda qo'llab-quvvatlanadigan video trek topilmadi")
}

func makeThumb(src, dst string) error {
	f, err := os.Open(src)
	if err != nil {
		return err
	}
	defer f.Close()
	img, _, err := image.Decode(bufio.NewReader(f))
	if err != nil {
		return err
	}
	b := img.Bounds()
	w, h := b.Dx(), b.Dy()
	const max = 480
	if w > max || h > max {
		if w >= h {
			h = h * max / w
			w = max
		} else {
			w = w * max / h
			h = max
		}
	}
	if w < 1 {
		w = 1
	}
	if h < 1 {
		h = 1
	}
	dstImg := image.NewRGBA(image.Rect(0, 0, w, h))
	draw.ApproxBiLinear.Scale(dstImg, dstImg.Bounds(), img, b, draw.Over, nil)
	out, err := os.OpenFile(dst, os.O_CREATE|os.O_TRUNC|os.O_WRONLY, 0o600)
	if err != nil {
		return err
	}
	defer out.Close()
	return jpeg.Encode(out, dstImg, &jpeg.Options{Quality: 80})
}

// Ext returns a safe extension for Content-Disposition names.
func Ext(mime string) string {
	return map[string]string{"image/png": "png", "image/jpeg": "jpg", "image/gif": "gif", "image/webp": "webp", "video/mp4": "mp4", "video/webm": "webm"}[mime]
}

